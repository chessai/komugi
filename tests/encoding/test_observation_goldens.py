"""KOM-002 §7 F -- acceptances #24-#27 over the committed observation goldens.

The four nodes ``docs/design/kom-002-input-planes-v2.md`` §7 F names, verbatim:

* ``test_movetype_coverage`` (#24) -- G2 contains at least one ply of each move
  class, and the counts are **recomputed from the replay**, never read out of
  the manifest.
* ``test_manifest_declares_its_source`` (#25) -- G1 says which of §6.1's two
  sources it came from, and agrees with the running plane map.
* ``test_golden_replay_matches_every_plane_digest`` (#26) -- replaying G1 and G2
  through ``Game`` reproduces every recorded per-ply scalar and all 128 plane
  digests; a mismatch names the first differing plane index and the ply.
* ``test_hand_written_plies_match`` (#26, rev 2 N12) -- expected values derived
  **by reading the board against the design's plane map**, not copied from the
  generator, for ply 0 of G1, G1's final ply, and every G2 ply whose
  ``last_move`` carries a tier ≠ 1 (§6.5).
* ``test_g1_reaches_occurrence_three`` (#27).

**Why the hand-written half exists** (§6.5): a golden generated by the code it
pins proves nothing on its own -- a plane-map error committed alongside the
golden is invisible forever, because every future run agrees with it.  So the
expected values here are re-derived from the *documents*: the FEN grammar
(``src/komugi/engine/fen.py``'s ``parse_fen``/``encode_fen``), the action
encoding's four blocks (``action_encoding``'s module docstring), and §2's plane
table plus §3.2's per-move-type ``to_tier`` rules.  Nothing in the derivation
below calls the encoder, the move generator or ``decode_cython_action``.

**The orientation shortcut this file leans on, stated once.**  §2 pins
``obs[p].reshape(81)[s]`` with ``s = r * 9 + (8 - f)``.  ``encode_fen`` writes
file 9 first (``9 - len(row)``), so the *column index within a FEN rank*, read
left to right with digits expanded, is exactly ``8 - f``.  Therefore

    s = 9 * <rank index in the FEN> + <column index within that rank>

and a FEN can be read straight into flat plane coordinates with no second
convention to keep honest.
"""

