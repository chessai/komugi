def test_manifest_declares_its_source(g1: Golden) -> None:
    """G1's manifest names one of §6.1's two sources and this plane map.

    Self-consistency, not provenance (rev 2, N10): the fallback branch's
    additional obligation -- recording in ``tickets/KOM-002.md`` what was
    searched under ``gungi-az-runs`` and why it failed -- is a merge check on
    the ticket, not something this file can assert.
    """
    manifest = g1.manifest
    assert manifest["source"] in ("v1-1600sim", "fallback-shuffle"), (
        f"G1's manifest source is {manifest['source']!r}, which is neither of "
        "§6.1's two sources"
    )
    # KOM-165: the committed goldens were generated under plane map 2 and are
    # NOT regenerated -- planes 115/120 rescale onto the running map exactly
    # (``rescaled_to_golden_cap``), which is what keeps them comparable.  Any
    # OTHER version is a golden this replay cannot interpret.
    assert int(manifest["plane_map_version"]) in (
        observation.PLANE_MAP_VERSION,
        GOLDEN_PLANE_MAP_VERSION,
    ), (
        f"G1 declares plane map version {manifest['plane_map_version']}, which "
        f"is neither this process's ({observation.PLANE_MAP_VERSION}) nor the "
        f"cap-rescalable one it was generated under ({GOLDEN_PLANE_MAP_VERSION})"
    )
    assert int(manifest["n_planes"]) == observation.observation_size()[0]
    assert int(manifest["n_planes"]) == N_PLANES
    assert str(manifest["generated_by"]) == "scripts/goldens/gen_observation_golden.py"
    assert str(manifest["git_sha"]) != "unknown", (
        "§6.5 binds the manifest to record the generating commit"
    )


# ---------------------------------------------------------------------------
# #26 -- the replay reproduces every digest
# ---------------------------------------------------------------------------


def test_golden_replay_matches_every_plane_digest(g1: Golden, g2: Golden) -> None:
    """Every ply of G1 and G2 replays to the recorded scalars and 128 digests.

    §6.4 is the specification of the failure message, not just of the failure:
    a plane inserted or removed anywhere below 128 must name *which* plane
    moved, at which ply, because a whole-array hash that only says "something
    changed" cannot localise a plane-map regression.

    **KOM-165.** The committed goldens carry plane map 2, whose planes 115 and
    120 were normalised by :data:`GOLDEN_CAP`.  Those two planes are compared
    after :func:`rescaled_to_golden_cap`, an exact float32 rescale, so the
    fixtures stay byte-identical and the other 126 digests stay the strict
    bit-identity check they always were.
    """
    for golden in (g1, g2):
        for entry in golden.plies:
            record = entry.record
            where = f"{golden.name} segment {entry.segment} ply {entry.ply}"

            assert entry.fen == str(record["fen"]), f"{where}: FEN differs"
            assert entry.turns == int(record["turns"]), f"{where}: turns differ"
            assert entry.turns < GOLDEN_CAP, (
                f"{where}: the golden reaches ply {entry.turns}, at or past the "
                f"{GOLDEN_CAP}-ply cap it was generated under; the recorded "
                "planes 115/120 are clipped there and the rescale below is no "
                "longer exact -- regenerate the golden"
            )
            assert entry.repetition_count == int(record["repetition_count"]), (
                f"{where}: repetition_count differs"
            )
            assert entry.progress_plies == int(record["progress_plies"]), (
                f"{where}: progress_plies differs"
            )
            expected_last = (
                None
                if record["last_move"] is None
                else tuple(int(value) for value in record["last_move"])
            )
            assert entry.last_move == expected_last, f"{where}: last_move differs"

            recorded = [str(digest) for digest in record["planes"]]
            assert len(recorded) == N_PLANES, (
                f"{where}: {len(recorded)} digests recorded for {N_PLANES} planes"
            )
            replayed = plane_digests(rescaled_to_golden_cap(entry.obs))
            assert len(replayed) == N_PLANES, (
                f"{where}: the encoder emitted {len(replayed)} planes"
            )
            first_difference = next(
                (
                    index
                    for index, (left, right) in enumerate(zip(replayed, recorded))
                    if left != right
                ),
                None,
            )
            if first_difference is not None:
                pytest.fail(
                    f"{where}: first differing plane index {first_difference} "
                    f"(replayed {replayed[first_difference]}, "
                    f"recorded {recorded[first_difference]}); "
                    f"{sum(1 for a, b in zip(replayed, recorded) if a != b)} of "
                    f"{N_PLANES} planes differ"
                )


