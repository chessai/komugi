# ---------------------------------------------------------------------------
# Reading a FEN by hand -- the grammar of fen.py's parse_fen/encode_fen
# ---------------------------------------------------------------------------


def fen_piece(code: str) -> tuple[int, int]:
    """``(type_index, colour_index)`` for one FEN letter; upper case is white."""
    return (FEN_CODE_TO_TYPE[code.lower()], 0 if code.isupper() else 1)


def parse_towers(fen: str) -> dict[int, tuple[tuple[int, int], ...]]:
    """Square -> its tower's ``(type_index, colour_index)``, tier 1 first.

    The placement field is nine ranks separated by ``/``; within a rank, a part
    containing ``:`` is one square holding a tower written bottom to top
    (``parse_fen`` assigns ``tier = z + 1`` over the split), everything else is
    a run of single-piece squares and digit-encoded empties.  Squares are keyed
    by the flat index of this module's docstring.
    """
    placement = fen.split(" ")[0]
    towers: dict[int, tuple[tuple[int, int], ...]] = {}
    ranks = placement.split("/")
    assert len(ranks) == 9, f"placement has {len(ranks)} ranks: {fen!r}"
    for rank_index, rank in enumerate(ranks):
        column = 0
        for part in rank.split("|"):
            if not part:
                continue
            if ":" in part:
                towers[rank_index * 9 + column] = tuple(
                    fen_piece(code) for code in part.split(":")
                )
                column += 1
                continue
            for char in part:
                if char.isdigit():
                    column += int(char)
                else:
                    towers[rank_index * 9 + column] = (fen_piece(char),)
                    column += 1
        assert column == 9, f"rank {rank_index} covers {column} squares: {fen!r}"
    return towers


def parse_hands(fen: str) -> dict[tuple[int, int], int]:
    """``(type_index, colour_index) -> count`` from the FEN's second field."""
    white, black = fen.split(" ")[1].split("/")
    hands: dict[tuple[int, int], int] = {}
    for text, colour in ((white, 0), (black, 1)):
        if text == "-":
            continue
        for offset in range(0, len(text), 2):
            hands[(FEN_CODE_TO_TYPE[text[offset].lower()], colour)] = int(
                text[offset + 1]
            )
    return hands


def fen_mover(fen: str) -> int:
    """0 (white) or 1 (black) -- the side to move in the FEN's third field."""
    return 0 if fen.split(" ")[2] == "w" else 1


# ---------------------------------------------------------------------------
# Reading an action id by hand -- action_encoding's four blocks
# ---------------------------------------------------------------------------


def move_classes(action: int, fen_before: str) -> tuple[str, ...]:
    """The move classes of *action* played at *fen_before* (#24's vocabulary).

    Derived from the id's block and the position it is played in, never from a
    decoded record:

    * A0 is "board move, no stack" -- a route lands on an empty square and a
      capture takes the enemy top, and nothing else lives in that block, so the
      target square's occupancy decides which.
    * A1 is "board move, stack" and carries the two-bit selector ``sel``:
      ``sel = 0`` is the plain tsuke, anything else converts, which is a betray
      (``action_encoding``'s selector table; §3.3 notes ``sel = 0`` decodes to
      ``MT_TSUKE``).
    * B and C are the arata blocks, split by id range exactly as §6.2's class
      list does (block C is the 終 variant).  Their one-bit ``bsel`` is set iff
      the drop converts the tier-1 enemy under the drop square.
    """
    if action < A1_START:
        _, to_sq = divmod(action - A0_START, 81)
        return ("capture",) if to_sq in parse_towers(fen_before) else ("route",)
    if action < B_START:
        plane = (action - A1_START) // 81
        return ("tsuke",) if plane % 4 == 0 else ("betray",)
    start = B_START if action < C_START else C_START
    plane = (action - start) // 81
    classes = ["arata", "arata_block_b" if action < C_START else "shu_block_c"]
    if plane % 2 == 1:
        classes.append("arata_conversion")
    return tuple(classes)


def derive_last_move(
    action: int, fen_before: str
) -> tuple[tuple[int, int, int, int], tuple[int, int]]:
    """``((from_sq, from_tier, to_sq, to_tier), (type_index, colour))``.

    The whole of §3.2's table, re-derived from the position the move is played
    in.  ``from_tier`` is the origin tower's height, because the mover is by
    construction its top; ``to_tier`` is

    * ``1`` for a route (empty target),
    * *(friendly pieces surviving in the target tower)* ``+ 1`` for a capture
      (§3.2's B1 correction -- a capture does **not** land at tier 1),
    * *(target height)* ``+ 1`` for a tsuke, a betray and an arata onto an
      occupied square, and ``1`` for an arata onto an empty one.

    An arata has no origin: ``from_sq = -1``, ``from_tier = 0``.
    """
    towers = parse_towers(fen_before)
    mover = fen_mover(fen_before)
    if action < A1_START:
        from_sq, to_sq = divmod(action - A0_START, 81)
        origin = towers[from_sq]
        target = towers.get(to_sq, ())
        to_tier = (
            1 if not target else sum(1 for _, colour in target if colour == mover) + 1
        )
        return (from_sq, len(origin), to_sq, to_tier), origin[-1]
    if action < B_START:
        plane, to_sq = divmod(action - A1_START, 81)
        from_sq = plane // 4
        origin = towers[from_sq]
        return (from_sq, len(origin), to_sq, len(towers.get(to_sq, ())) + 1), origin[-1]
    start = B_START if action < C_START else C_START
    plane, to_sq = divmod(action - start, 81)
    return (-1, 0, to_sq, len(towers.get(to_sq, ())) + 1), (plane // 2, mover)


def is_progress_move(action: int, fen_before: str) -> bool:
    """§3.3's operational rule: a capture, a betrayal or an arata makes progress."""
    if action >= B_START:
        return True
    if action >= A1_START:
        return ((action - A1_START) // 81) % 4 != 0
    return (action - A0_START) % 81 in parse_towers(fen_before)


def occupancy_plane(type_index: int, tier: int, colour: int) -> int:
    """§2's occupancy formula, ``ti * 6 + (tier - 1) * 2 + ci``."""
    return type_index * 6 + (tier - 1) * 2 + colour


