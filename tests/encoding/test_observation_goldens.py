def nonzero_cells(obs: npt.NDArray[np.float32], plane: int) -> dict[int, float]:
    """``{square: value}`` over the nonzero cells of *plane*, flattened by §2."""
    flat = obs[plane].reshape(81)
    return {index: float(flat[index]) for index in range(81) if flat[index] != 0.0}


def constant_value(obs: npt.NDArray[np.float32], plane: int) -> float:
    """The value of a plane §2 declares constant, checked to be constant."""
    plane_array = obs[plane]
    assert float(plane_array.min()) == float(plane_array.max()), (
        f"plane {plane} is not constant"
    )
    return float(plane_array[0, 0])


# ---------------------------------------------------------------------------
# #24 -- move-type coverage, recomputed
# ---------------------------------------------------------------------------


def test_movetype_coverage(g2: Golden) -> None:
    """G2 covers every move class, counted off the replay rather than the file.

    §7 #24 is explicit that the test **recomputes** the counts: a manifest that
    merely claims coverage is a string, and the whole point of G2 is that
    "the golden passes" cannot mean "the golden covers nothing".  Every action
    is classified from its own id and the position it was played in
    (:func:`move_classes`), and the manifest is then required to agree.
    """
    counts: dict[str, int] = {}
    previous_fen: str | None = None
    for entry in g2.plies:
        if entry.action is not None:
            assert previous_fen is not None
            for name in move_classes(entry.action, previous_fen):
                counts[name] = counts.get(name, 0) + 1
        previous_fen = entry.fen

    missing = [name for name in REQUIRED_CLASSES if counts.get(name, 0) < 1]
    assert not missing, (
        f"G2 covers {sorted(counts)} but #24 requires at least one ply of each "
        f"of {list(REQUIRED_CLASSES)}; missing {missing}"
    )

    declared = {
        str(name): int(count)
        for name, count in g2.manifest["move_class_counts"].items()
    }
    assert counts == declared, (
        "the recomputed move-class counts disagree with the manifest: "
        f"recomputed {dict(sorted(counts.items()))} vs "
        f"declared {dict(sorted(declared.items()))}"
    )


