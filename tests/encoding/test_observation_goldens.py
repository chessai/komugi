def test_g1_reaches_occurrence_three(g1: Golden) -> None:
    """G1 replays into a third occurrence, and R3 fires exactly there.

    Without this, G1 pins the repetition planes at their all-zero codeword and
    is a golden of nothing (#27).  ``PURE_SHUFFLE`` repeats its position every
    four plies from position P, so the occurrence counts run 1,1,1,1 / 2,2,2,2
    / 3 -- hand-derived from the cycle length, not read off the file.
    """
    counts = [entry.repetition_count for entry in g1.plies]
    assert max(counts) >= 3, f"G1's occurrence counts are {counts}"
    if g1.manifest["source"] == "fallback-shuffle":
        # The four-ply cycle, counted by hand: every position of the shuffle is
        # new on plies 0-3, back for the second time on 4-7, and position P is
        # back for the third time on ply 8, which is where the line stops.
        assert counts == [1, 1, 1, 1, 2, 2, 2, 2, 3]

    for entry in g1.plies:
        assert constant_value(entry.obs, PLANE_R2) == (
            1.0 if entry.repetition_count >= 2 else 0.0
        )
        assert constant_value(entry.obs, PLANE_R3) == (
            1.0 if entry.repetition_count >= 3 else 0.0
        )
