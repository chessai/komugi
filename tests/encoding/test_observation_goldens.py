@dataclass(frozen=True)
class ReplayPly:
    """One replayed ply, beside the golden record it is compared against."""

    segment: int
    ply: int
    action: int | None
    fen: str
    turns: int
    repetition_count: int
    progress_plies: int
    last_move: tuple[int, int, int, int] | None
    obs: npt.NDArray[np.float32]
    record: dict[str, Any]


@dataclass(frozen=True)
class Golden:
    """A golden file and the replay of every ply in it."""

    name: str
    payload: dict[str, Any]
    plies: tuple[ReplayPly, ...]

    @property
    def manifest(self) -> dict[str, Any]:
        """The file's top-level manifest (§6.3)."""
        manifest: dict[str, Any] = self.payload["manifest"]
        return manifest

    def ply_at(self, segment: int, ply: int) -> ReplayPly:
        """The replayed ply at (*segment*, *ply*)."""
        for entry in self.plies:
            if entry.segment == segment and entry.ply == ply:
                return entry
        raise AssertionError(f"{self.name} has no segment {segment} ply {ply}")


def load_golden(name: str) -> dict[str, Any]:
    """The golden file *name*, parsed.  Read-only: no test ever writes here."""
    with (GOLDENS_DIR / name).open(encoding="utf-8") as handle:
        payload: dict[str, Any] = json.load(handle)
    return payload


def plane_digests(obs: npt.NDArray[np.float32]) -> list[str]:
    """§6.3's digest per plane: ``sha256(float32 bytes, C order)[:8]``."""
    return [
        hashlib.sha256(np.ascontiguousarray(plane).tobytes()).hexdigest()[:8]
        for plane in obs
    ]


def rescaled_to_golden_cap(
    obs: npt.NDArray[np.float32],
) -> npt.NDArray[np.float32]:
    """*obs* with planes 115 and 120 put back on :data:`GOLDEN_CAP` (KOM-165).

    The committed goldens were generated at a 256-ply cap; this process runs at
    :data:`MAX_TURNS`.  The two cap-normalised planes hold ``k / cap`` for an
    integer ``k`` below the cap, and both caps are powers of two, so multiplying
    by ``MAX_TURNS / GOLDEN_CAP`` moves the float32 exponent and nothing else:
    the rescaled plane is bit-for-bit the plane the generator hashed, and its
    digest is comparable to the recorded one WITHOUT regenerating the fixture
    (design review F4's argument, applied to the per-plane digests).

    Every other plane is independent of the cap, so this is the whole of the
    difference between a plane-map-2 golden and a plane-map-3 replay.

    Exact only while no golden ply reaches :data:`GOLDEN_CAP` -- past it the
    recorded plane is clipped to 1.0 and this one is not.  The caller asserts
    that rather than assuming it.
    """
    rescaled = obs.copy()
    factor = np.float32(MAX_TURNS / GOLDEN_CAP)
    for plane in CAP_NORMALISED_PLANES:
        rescaled[plane] *= factor
    return rescaled


def _snapshot(game: Game, record: dict[str, Any]) -> ReplayPly:
    """The replay's own view of the position *record* claims to describe."""
    last_move = game._last_move
    obs: npt.NDArray[np.float32] = np.ascontiguousarray(
        game.observation(), dtype=np.float32
    )
    action = record["action"]
    return ReplayPly(
        segment=int(record["segment"]),
        ply=int(record["ply"]),
        action=None if action is None else int(action),
        fen=str(board_to_fen(game._board)),
        turns=int(game.turns),
        repetition_count=int(game.repetition_count()),
        progress_plies=int(game._progress_plies),
        last_move=(
            None
            if last_move is None
            else (
                int(last_move[0]),
                int(last_move[1]),
                int(last_move[2]),
                int(last_move[3]),
            )
        ),
        obs=obs,
        record=record,
    )


@lru_cache(maxsize=None)
def replay(name: str) -> Golden:
    """Replay every segment of golden *name* through the real ``Game`` path.

    A segment starts from its own ``start_fen``, or -- when that is ``null`` --
    from its mode's start position, which is what the generator's ``Game()``
    produces.  Each segment's first record is the one with ``action: null``.
    """
    payload = load_golden(name)
    segments: list[dict[str, Any]] = list(payload["segments"])
    plies: list[ReplayPly] = []
    game: Game | None = None
    for record in payload["plies"]:
        action = record["action"]
        if action is None:
            header = segments[int(record["segment"])]
            start_fen = header["start_fen"]
            if start_fen is None:
                start_fen = MODE_START_FEN[str(header["mode"])]
            game = Game(board_from_fen(str(start_fen)))
        else:
            assert game is not None, f"{name}: a ply precedes its segment head"
            game.play_action(int(action))
        assert game is not None
        plies.append(_snapshot(game, record))
    return Golden(name=name, payload=payload, plies=tuple(plies))


