// ---- sequence records: replay + terminal ply --------------------------------

// KOM-1111 (verifier): also compares the final verdict against
// `record.komugi.terminal` (not just the ply it was reached at), and
// asserts the rootGame-reconstructed Game itself is terminal at that ply
// (not merely that its stamp came back HISTORY_PRESENT) -- a sequence with
// no false_checkmate-class record never exercises the KOM-1110 fix
// (checked separately above / in false_mate.test.ts), so this must agree
// under BOTH 'komugi' and 'gungijs'.
function assertKomugiSequencePly(rules: RulesProfile): void {
  for (const record of sequences) {
    const { sans, terminalPly, finalFen } = replaySequence(record, rules);
    assert.equal(terminalPly, record.komugi.terminalPly, `${record.id} (${rules}): terminal ply`);

    const { game, stamp } = rootGame(finalFen, sans, sequenceStart(record), rules);
    assert.equal(stamp, HISTORY_PRESENT, `${record.id} (${rules}): rootGame stamp`);
    assert.deepEqual(verdictOf(game), record.komugi.terminal, `${record.id} (${rules}): final verdict`);
    if (terminalPly !== null) {
      const [whiteWins, blackWins, draw] = game.winState();
      assert.ok(
        whiteWins || blackWins || draw,
        `${record.id} (${rules}): rootGame-returned Game not terminal at ply ${terminalPly}`,
      );
    }
  }
}

test('komugi: every sequence record replays to the komugi terminal ply (rootGame stamp present)', () => {
  assertKomugiSequencePly('komugi');
});

test('gungijs: every sequence record replays to the komugi terminal ply (rootGame stamp present)', () => {
  assertKomugiSequencePly('gungijs');
});

// KOM-1107: now that gameFromHistory/replaySequence use RepetitionRule.FULL
// under 'ligungi' (rule (5)), the repetition_key class's own ply mismatches
// (previously 31, against the old PLACEMENT key) flip to 0 -- every class
// is 0, none = 0 included.
const LIGUNGI_SEQUENCE_PLY_MISMATCH_COUNTS: Record<KnownClass, number> = {
  none: 0,
  self_exposure: 0,
  self_exposure_checkmate_claim: 0,
  archer_blocking: 0,
  betrayal_partial: 0,
  stalemate_scoring: 0,
  insufficient_material: 0,
  repetition_key: 0,
  false_checkmate: 0,
};

test('ligungi: pinned sequence terminal-ply mismatch count (all 0, incl. repetition_key -- KOM-1107 FULL key)', () => {
  function mismatches(record: SequenceRecord): boolean {
    const { terminalPly, sans, finalFen } = replaySequence(record, 'ligungi');
    const { stamp } = rootGame(finalFen, sans, sequenceStart(record), 'ligungi');
    assert.equal(stamp, HISTORY_PRESENT, `${record.id} (ligungi): rootGame stamp`);
    return terminalPly !== record.ligungi.terminalPly;
  }
  const counts = tallyByClass(sequences, mismatches);
  console.log('ligungi sequence terminal-ply mismatch counts by class:', counts);
  assert.deepEqual(counts, LIGUNGI_SEQUENCE_PLY_MISMATCH_COUNTS);
});

// KOM-1107 SCOPE NOTE 2026-11-14: an EXACT-MATCH test over every
// repetition_key-ONLY sequence record (classes === ['repetition_key'], 31 of
// them), with no observed-count pin -- every one of these must now agree
// with ligungi's own terminalPly AND terminal-ness/winner exactly, under
// RepetitionRule.FULL.
const REPETITION_KEY_ONLY_SEQUENCES = sequences.filter(
  (r) => r.classes.length === 1 && r.classes[0] === 'repetition_key',
);

test('ligungi_oracle.json: has 31 repetition_key-only sequence records', () => {
  assert.equal(REPETITION_KEY_ONLY_SEQUENCES.length, 31);
});

test('ligungi: every repetition_key-only sequence record matches ligungi exactly (terminal ply + verdict, no pin)', () => {
  for (const record of REPETITION_KEY_ONLY_SEQUENCES) {
    const { terminalPly, sans, finalFen } = replaySequence(record, 'ligungi');
    assert.equal(terminalPly, record.ligungi.terminalPly, `${record.id}: terminal ply`);
    const { game, stamp } = rootGame(finalFen, sans, sequenceStart(record), 'ligungi');
    assert.equal(stamp, HISTORY_PRESENT, `${record.id}: rootGame stamp`);
    assert.equal(
      verdictsDisagree(verdictOf(game), record.ligungi.terminal),
      false,
      `${record.id}: terminal-ness/winner must agree with record.ligungi.terminal`,
    );
  }
});

// KOM-1107 rule (5): a repetition_key sequence ends LATER under 'ligungi'
// (FULL key, threshold 4 over board+hands+turn+draft) than under 'komugi'
// (PLACEMENT key, cells only) -- the exact property the FULL key switch is
// for (docs comment on replaySequence/gameFromHistory).
test('ligungi: a repetition_key sequence ends later under ligungi (FULL) than under komugi (PLACEMENT)', () => {
  const record = REPETITION_KEY_ONLY_SEQUENCES[0];
  const underKomugi = replaySequence(record, 'komugi');
  const underLigungi = replaySequence(record, 'ligungi');
  assert.equal(underKomugi.terminalPly, record.komugi.terminalPly, 'komugi terminal ply');
  assert.equal(underLigungi.terminalPly, record.ligungi.terminalPly, 'ligungi terminal ply');
  assert.ok(
    underKomugi.terminalPly !== null && underLigungi.terminalPly !== null,
    'both replays must reach a terminal ply',
  );
  assert.ok(
    (underLigungi.terminalPly as number) > (underKomugi.terminalPly as number),
    `expected ligungi (${underLigungi.terminalPly}) to end later than komugi (${underKomugi.terminalPly})`,
  );
});
