// KOM-1111: the ligungi oracle fixture's terminal-verdict dimension, kept
// separate from the legal-move-set dimension (oracle_legal.test.ts).
//
// Position records: (a) komugi/gungijs verdict (Game.winState(), read off in
// Komugi's own vocabulary by oracle_helpers.verdictOf) must equal
// `record.komugi.terminal` exactly -- same engine family, same vocabulary,
// no exceptions. (b) ligungi: pinned per-class mismatch counts, comparing
// only terminal-ness + winner (never the `reason` spelling -- ligungi's own
// vocabulary differs, e.g. 'mate' vs 'checkmate'/'stalemate', so a spelling
// diff alone is not one of the 8 named divergence classes).
//
// Sequence records: every sequence is replayed through rootGame(endFen,
// sans, start, rules) with stamp present; komugi/gungijs must land at
// `record.komugi.terminalPly`, ligungi's pinned mismatch count is against
// `record.ligungi.terminalPly`.

import assert from 'node:assert/strict';
import { test } from 'node:test';

import type { RulesProfile } from '../src/repetition.ts';
import { HISTORY_PRESENT, rootGame } from '../src/root.ts';
import {
  type KnownClass,
  type PositionRecord,
  type SequenceRecord,
  gameForPosition,
  loadOracleFixture,
  positionRecords,
  replaySequence,
  sequenceRecords,
  sequenceStart,
  tallyByClass,
  verdictOf,
  verdictsDisagree,
} from './oracle_helpers.ts';

const fixture = loadOracleFixture();
const positions = positionRecords(fixture);
const sequences = sequenceRecords(fixture);

test('ligungi_oracle.json: has sequence records', () => {
  assert.ok(sequences.length > 0, 'expected at least one sequence record');
});

// ---- position records: verdict dimension -----------------------------------

function assertKomugiVerdicts(rules: RulesProfile): void {
  for (const record of positions) {
    const game = gameForPosition(record, rules);
    const got = verdictOf(game);
    assert.deepEqual(got, record.komugi.terminal, `${record.id} (${rules})`);
  }
}

test('gungijs: every position record verdict equals komugi.terminal', () => {
  assertKomugiVerdicts('gungijs');
});

// KOM-1110: `record.komugi.terminal` was generated by the OLD (pre-KOM-1109)
// engine, so it still scores every false_checkmate record checkmate. Under
// 'komugi' this unit now applies the fix (capturing the opposing marshal is
// an escape -- false_mate.test.ts), so those records diverge from the
// fixture's own komugi.terminal field ON PURPOSE: this is not silently
// dropping records, it is the fixture's pinned old-engine verdict
// disagreeing with the new, correct one. `classes` is not a partition (a
// record can carry several at once -- oracle_helpers.ts's own note), and
// every false_checkmate record here also happens to carry self_exposure
// (all 30) or self_exposure_checkmate_claim (4 of those 30), hence both
// non-zero too; printed-then-pinned, per this unit's own convention.
// KOM-1191: 35/6/35 -> 30/4/30 once the bot-match-sourced fixture records
// were filtered out (strip_bot_records.mjs); every other class stays 0.
const KOMUGI_TERMINAL_MISMATCH_COUNTS: Record<KnownClass, number> = {
  none: 0,
  self_exposure: 30,
  self_exposure_checkmate_claim: 4,
  archer_blocking: 0,
  betrayal_partial: 0,
  stalemate_scoring: 0,
  insufficient_material: 0,
  repetition_key: 0,
  false_checkmate: 30,
};

test('komugi: pinned per-class verdict mismatch count against the OLD-engine komugi.terminal (false_checkmate = 30, KOM-1109/1110 fix)', () => {
  function mismatches(record: PositionRecord): boolean {
    const game = gameForPosition(record, 'komugi');
    return JSON.stringify(verdictOf(game)) !== JSON.stringify(record.komugi.terminal);
  }
  const counts = tallyByClass(positions, mismatches);
  console.log('komugi terminal-verdict mismatch counts by class (vs OLD-engine komugi.terminal):', counts);
  assert.deepEqual(counts, KOMUGI_TERMINAL_MISMATCH_COUNTS);
});

